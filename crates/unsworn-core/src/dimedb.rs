fn resolve_tag_group(
    kind: &str,
    items: &[(String, Option<u8>)],
    locked: &BTreeMap<String, u8>,
    require_nonzero: bool,
) -> Result<(Vec<u8>, BTreeMap<String, u8>), String> {
    let mut next_lock = locked.clone();
    let mut used_tags: std::collections::BTreeSet<u8> = locked.values().copied().collect();
    let mut claimed_in_schema = std::collections::BTreeSet::new();

    for (name, explicit) in items {
        if let Some(t) = *explicit {
            if require_nonzero && t == 0 {
                return Err(format!(
                    "{kind} `{name}` tag 0 is outside supported range 1..=255"
                ));
            }
            if let Some(&prev) = locked.get(name)
                && prev != t
            {
                return Err(format!(
                    "{kind} `{name}` has explicit tag {t}, which conflicts with dimedb.lock tag {prev}"
                ));
            }
            if !claimed_in_schema.insert(t) {
                return Err(format!("duplicate {kind} tag {t} for `{name}`"));
            }
            used_tags.insert(t);
            next_lock.insert(name.clone(), t);
        }
    }

    let mut resolved = Vec::with_capacity(items.len());
    for (name, explicit) in items {
        if let Some(t) = *explicit {
            resolved.push(t);
            continue;
        }
        if let Some(&prev) = locked.get(name) {
            if !claimed_in_schema.insert(prev) {
                return Err(format!(
                    "{kind} `{name}` locked tag {prev} conflicts with another explicit {kind} tag"
                ));
            }
            resolved.push(prev);
        } else {
            let tag = (1u8..=255)
                .find(|t| !used_tags.contains(t))
                .ok_or_else(|| format!("exhausted all 255 available {kind} tags"))?;
            used_tags.insert(tag);
            claimed_in_schema.insert(tag);
            next_lock.insert(name.clone(), tag);
            resolved.push(tag);
        }
    }
    Ok((resolved, next_lock))
}

impl DimeSchema {
    pub fn from_toml(src: &str) -> Result<Self, String> {
        let (schema, _, _) = Self::from_toml_with_lock(src, None)?;
        Ok(schema)
    }

    pub fn from_toml_with_lock(
        src: &str,
        lock_toml: Option<&str>,
    ) -> Result<(Self, TagLock, bool), String> {
        let raw: RawDimeSchema =
            toml::from_str(src).map_err(|e| format!("invalid dimedb.toml: {e}"))?;
        let existing_lock = match lock_toml {
            Some(s) => TagLock::from_toml(s)?,
            None => TagLock::default(),
        };

        let table_pairs: Vec<(String, Option<u8>)> =
            raw.tables.iter().map(|t| (t.name.clone(), t.tag)).collect();
        let (table_tags, locked_tables) =
            resolve_tag_group("table", &table_pairs, &existing_lock.tables, true)?;

        let cmd_pairs: Vec<(String, Option<u8>)> = raw
            .commands
            .iter()
            .map(|c| (c.name.clone(), c.tag))
            .collect();
        let (cmd_tags, locked_commands) =
            resolve_tag_group("command", &cmd_pairs, &existing_lock.commands, false)?;

        let reply_pairs: Vec<(String, Option<u8>)> = raw
            .replies
            .iter()
            .map(|r| (r.name.clone(), r.tag))
            .collect();
        let (reply_tags, locked_replies) =
            resolve_tag_group("reply", &reply_pairs, &existing_lock.replies, false)?;

        let tables: Vec<DimeTable> = raw
            .tables
            .into_iter()
            .zip(table_tags)
            .map(|(t, tag)| DimeTable {
                name: t.name,
                tag,
                key: t.key,
                fields: t.fields,
                index: t.index,
                indexes: t.indexes,
            })
            .collect();
        let commands = raw
            .commands
            .into_iter()
            .zip(cmd_tags)
            .map(|(c, tag)| DimeVariant {
                name: c.name,
                tag,
                fields: c.fields,
            })
            .collect();
        let replies = raw
            .replies
            .into_iter()
            .zip(reply_tags)
            .map(|(r, tag)| DimeVariant {
                name: r.name,
                tag,
                fields: r.fields,
            })
            .collect();

        let mut seen_tags = std::collections::BTreeSet::new();
        for t in &tables {
            if t.tag == 0 {
                return Err(format!(
                    "table `{}` tag 0 is outside supported range 1..=255",
                    t.name
                ));
            }
            if !seen_tags.insert(t.tag) {
                return Err(format!("duplicate table tag {} for `{}`", t.tag, t.name));
            }
            if let Some(idx) = &t.index
                && !t.fields.iter().any(|f| f.name == idx.field)
            {
                return Err(format!(
                    "table `{}` index `{}` references unknown field `{}`",
                    t.name, idx.name, idx.field
                ));
            }
            for field_name in &t.indexes {
                if !t.fields.iter().any(|f| f.name == *field_name) {
                    return Err(format!(
                        "table `{}` indexes references unknown field `{field_name}`",
                        t.name
                    ));
                }
            }
        }

        let updated_lock = TagLock {
            version: 1,
            tables: locked_tables,
            commands: locked_commands,
            replies: locked_replies,
        };
        let lock_dirty = lock_toml.is_none() || updated_lock != existing_lock;
        Ok((
            Self {
                app: raw.app,
                tables,
                commands,
                replies,
            },
            updated_lock,
            lock_dirty,
        ))
    }
}

/// Converts `PascalCase` (e.g. `CreateAccount`) to `snake_case` (`create_account`).
pub fn to_snake(name: &str) -> String {
    let mut out = String::with_capacity(name.len() + 4);
    for (i, ch) in name.chars().enumerate() {
        if ch.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(ch.to_ascii_lowercase());
        } else {
            out.push(ch);
        }
    }
    out
}

/// Maps a `dimedb.toml` wire type string to a JSON Schema object.
pub fn wire_type_to_json_schema(ty: &str) -> Value {
    let ty = ty.trim();
    match ty {
        "()" => json!({ "type": "null" }),
        "bool" => json!({ "type": "boolean" }),
        "u8" | "u16" | "u32" | "u64" => json!({ "type": "integer", "minimum": 0 }),
        "i8" | "i16" | "i32" | "i64" => json!({ "type": "integer" }),
        "u128" | "i128" | "String" => json!({ "type": "string" }),
        _ if ty.starts_with("Option<") && ty.ends_with('>') => {
            let inner = wire_type_to_json_schema(&ty[7..ty.len() - 1]);
            json!({ "anyOf": [inner, { "type": "null" }] })
        }
        _ if ty.starts_with("Vec<") && ty.ends_with('>') => {
            let inner = wire_type_to_json_schema(&ty[4..ty.len() - 1]);
            json!({ "type": "array", "items": inner })
        }
        _ => json!({}),
    }
}

/// JSON Schema for a mutating dimeDB command (requires `request_id` + command fields).
pub fn command_input_schema(cmd: &DimeVariant) -> Value {
    let mut props = Map::new();
    props.insert(
        "request_id".into(),
        json!({
            "description": "Idempotency key (UUIDv7 string or non-negative integer). Reuse the same request_id on retries to guarantee at-most-once execution.",
            "anyOf": [{ "type": "string" }, { "type": "integer", "minimum": 0 }]
        }),
    );
    let mut required = vec![Value::String("request_id".into())];
    for f in &cmd.fields {
        props.insert(f.name.clone(), wire_type_to_json_schema(&f.ty));
        required.push(Value::String(f.name.clone()));
    }
    json!({
        "type": "object",
        "properties": props,
        "required": required,
        "additionalProperties": false
    })
}

/// JSON Schema for `dimedb.lookup` / `dimedb_lookup`.
pub fn lookup_input_schema() -> Value {
    json!({
        "type": "object",
        "properties": {
            "request_id": {
                "description": "The request_id (UUIDv7 string or integer) to look up.",
                "anyOf": [{ "type": "string" }, { "type": "integer", "minimum": 0 }]
            }
        },
        "required": ["request_id"],
        "additionalProperties": false
    })
}

/// JSON Schema for `dimedb.get.<table>` / `dimedb_get_<table>`.
pub fn get_input_schema(table: &DimeTable) -> Value {
    json!({
        "type": "object",
        "properties": {
            "key": wire_type_to_json_schema(&table.key)
        },
        "required": ["key"],
        "additionalProperties": false
    })
}

/// JSON Schema for `dimedb.list.<table>` / `dimedb_list_<table>`.
pub fn list_input_schema(table: &DimeTable) -> Value {
    let key_schema = wire_type_to_json_schema(&table.key);
    json!({
        "type": "object",
        "properties": {
            "cursor": {
                "description": "Optional primary key cursor returned by a previous list call.",
                "anyOf": [key_schema, { "type": "null" }]
            },
            "limit": {
                "description": "Maximum number of rows to return (default 50, max 1000).",
                "type": "integer",
                "minimum": 1,
                "maximum": 1000
            }
        },
        "additionalProperties": false
    })
}

/// JSON Schema for `dimedb.find.<table>.by_<field>` / `dimedb_find_<table>_by_<field>`.
pub fn find_input_schema(index: &ResolvedDimeIndex) -> Value {
    json!({
        "type": "object",
        "properties": {
            "value": wire_type_to_json_schema(&index.ty),
            "limit": {
                "description": "Maximum number of matching rows to return (default 50, max 1000).",
                "type": "integer",
                "minimum": 1,
                "maximum": 1000
            }
        },
        "required": ["value"],
        "additionalProperties": false
    })
}

/// Constructs a virtual [`HandlerRef`] routed to the in-process or remote
/// dimeDB backend.
pub fn handler_ref(op: &str) -> HandlerRef {
    HandlerRef {
        raw: format!("{RUNTIME}:{op}"),
        file: RUNTIME.to_string(),
        name: Some(op.to_string()),
        runtime: RUNTIME.to_string(),
    }
}
