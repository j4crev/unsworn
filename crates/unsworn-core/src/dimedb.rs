/// Built-in virtual runtime name for dimeDB handlers (`ctx.call` and MCP tools).
pub const RUNTIME: &str = "dimedb";

fn default_lock_version() -> u32 {
    1
}

/// Persisted `dimedb.lock` mapping table, command, and reply names to stable
/// 1-byte wire tags so developers never have to assign `tag = N` by hand.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct TagLock {
    #[serde(default = "default_lock_version")]
    pub version: u32,
    #[serde(default)]
    pub tables: BTreeMap<String, u8>,
    #[serde(default)]
    pub commands: BTreeMap<String, u8>,
    #[serde(default)]
    pub replies: BTreeMap<String, u8>,
}

impl Default for TagLock {
    fn default() -> Self {
        Self {
            version: 1,
            tables: BTreeMap::new(),
            commands: BTreeMap::new(),
            replies: BTreeMap::new(),
        }
    }
}

impl TagLock {
    pub fn from_toml(src: &str) -> Result<Self, String> {
        toml::from_str(src).map_err(|e| format!("invalid dimedb.lock: {e}"))
    }

    pub fn to_toml(&self) -> String {
        let body = toml::to_string_pretty(self).unwrap_or_default();
        format!(
            "# Auto-generated by dimedb. Commit this file to keep binary tags stable.\n{body}"
        )
    }

    /// Computes the sibling lock path for a relative schema path (e.g. `dimedb.toml` -> `dimedb.lock`).
    pub fn path_for(schema_path: &str) -> String {
        match schema_path.rsplit_once('.') {
            Some((stem, ext)) if !ext.contains('/') => format!("{stem}.lock"),
            _ => format!("{schema_path}.lock"),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct DimeIndex {
    pub name: String,
    pub field: String,
    #[serde(rename = "type")]
    pub ty: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedDimeIndex {
    pub name: String,
    pub field: String,
    pub ty: String,
}

/// Parsed `dimedb.toml` schema (subset needed for routing, validation, and MCP).
#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct DimeSchema {
    pub app: DimeApp,
    #[serde(default)]
    pub tables: Vec<DimeTable>,
    #[serde(default)]
    pub commands: Vec<DimeVariant>,
    #[serde(default)]
    pub replies: Vec<DimeVariant>,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct DimeApp {
    pub name: String,
    pub version: u32,
}

#[derive(Debug, Clone, PartialEq, Eq, Deserialize, Serialize)]
pub struct DimeTable {
    pub name: String,
    pub tag: u8,
    pub key: String,
    #[serde(default)]
    pub fields: Vec<DimeField>,
    #[serde(default)]
    pub index: Option<DimeIndex>,
    #[serde(default)]
    pub indexes: Vec<String>,
}

impl DimeTable {
    pub fn resolved_indexes(&self) -> Vec<ResolvedDimeIndex> {
        let mut out = Vec::new();
        let mut seen = std::collections::BTreeSet::new();
        if let Some(idx) = &self.index
            && seen.insert(idx.field.clone())
        {
            out.push(ResolvedDimeIndex {
                name: idx.name.clone(),
                field: idx.field.clone(),
                ty: idx.ty.clone(),
            });
        }
        for field_name in &self.indexes {
            if !seen.insert(field_name.clone()) {
                continue;
            }
            if let Some(f) = self.fields.iter().find(|f| f.name == *field_name) {
                out.push(ResolvedDimeIndex {
                    name: format!("by_{field_name}"),
                    field: field_name.clone(),
                    ty: f.ty.clone(),
                });
            }
        }
        out
    }
}

