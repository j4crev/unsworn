fn project_with(config: &str, files: &[(&str, &str)]) -> Project {
    let mut all = vec![("unsworn.toml", config)];
    all.extend_from_slice(files);
    let host = MemHost::with(&all);
    let compiled = compile_symbolic(&host, "unsworn.toml");
    let errors: Vec<String> = compiled
        .diagnostics
        .iter()
        .filter(|d| d.is_error())
        .map(ToString::to_string)
        .collect();
    assert!(errors.is_empty(), "{errors:?}");
    compiled.project.unwrap()
}

#[test]
fn a_handler_for_routes_that_differ_gets_each_shape() {
    const ITEMS: &str = r#"
[runtimes.ts]
extensions = [".ts"]
command = "bun"

[[route]]
path = "/items/{id}"
method = "GET"
handler = "src/items.ts#item"

[[route]]
path = "/items/{id}"
method = "PUT"
handler = "src/items.ts#item"
body = { type = "object", required = ["name"], properties = { name = { type = "string" } } }
response = { type = "string" }

[[route]]
path = "/things/{id}"
method = "GET"
handler = "src/items.ts#item"
"#;
    let p = project_with(ITEMS, &[("src/items.ts", "")]);
    let out = generate(&p, Lang::TypeScript, &Options::default());
    assert!(
        out.contains("/** GET /items/{id}, GET /things/{id}, PUT /items/{id} */\nexport type Item = Handler<\n  | {\n    params: {\n      id: string;\n    };\n  }\n  | {\n    params: {\n      id: string;\n    };\n    json: {\n      name: string;\n    };\n  }\n>;\n"),
        "{out}"
    );
    assert!(
        out.contains("export type ItemPUTItemsIdResponse = string;"),
        "{out}"
    );
    let p = project_with(&ITEMS.replace(".ts", ".py"), &[("src/items.py", "")]);
    let out = generate(&p, Lang::Python, &Options::default());
    assert!(out.contains("ItemGETItemsIdRequest = Request["), "{out}");
    assert!(out.contains("ItemPUTItemsIdRequest = Request[ItemPUTItemsIdParams, dict[str, Any], ItemPUTItemsIdBody]"), "{out}");
}

