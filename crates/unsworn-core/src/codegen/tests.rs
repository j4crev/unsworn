const CONFIG: &str = r#"
[runtimes.ts]
extensions = [".ts"]
command = "bun"

[runtimes.py]
extensions = [".py"]
command = "python3"

[runtimes.go]
extensions = [".go"]
command = "./worker"

[runtimes.rs]
extensions = [".rs"]
command = "./worker"

[[route]]
path = "/users/{id}"
method = "GET"
handler = "src/users.EXT#get_user"
params = { id = { type = "integer", min = 1 } }
query = { limit = { type = "integer", default = 20 }, q = { type = "string" }, tag = { type = "array", items = "string" } }
response = "schemas/user.json"

[[route]]
path = "/users"
method = "POST"
handler = "src/users.EXT#create_user"
body = "schemas/new-user.json"

[[route]]
path = "/files/{*path}"
handler = "src/files.EXT"
"#;

const USER: &str = r#"{
  "type": "object",
  "required": ["id", "name"],
  "properties": {
    "id": {"type": "integer"},
    "name": {"type": "string"},
    "email": {"type": ["string", "null"]}
  }
}"#;

const NEW_USER: &str = r##"{
  "type": "object",
  "required": ["name", "role"],
  "properties": {
    "name": {"type": "string"},
    "role": {"enum": ["admin", "member"]},
    "address": {"$ref": "#/$defs/address"},
    "tags": {"type": "array", "items": {"type": "string"}},
    "x-labels": {"type": "object", "additionalProperties": {"type": "integer"}}
  },
  "$defs": {
    "address": {
      "type": "object",
      "required": ["city"],
      "properties": {"city": {"type": "string"}, "zip": {"type": "string"}}
    }
  }
}"##;

fn generated(lang: Lang, ext: &str) -> String {
    let config = CONFIG.replace("EXT", ext);
    let users = format!("src/users.{ext}");
    let files = format!("src/files.{ext}");
    let host = MemHost::with(&[
        ("unsworn.toml", &config),
        ("schemas/user.json", USER),
        ("schemas/new-user.json", NEW_USER),
        (&users, ""),
        (&files, ""),
    ]);
    let compiled = compile_symbolic(&host, "unsworn.toml");
    let errors: Vec<String> = compiled
        .diagnostics
        .iter()
        .filter(|d| d.is_error())
        .map(ToString::to_string)
        .collect();
    assert!(errors.is_empty(), "{errors:?}");
    generate(&compiled.project.unwrap(), lang, &Options::default())
}

#[test]
