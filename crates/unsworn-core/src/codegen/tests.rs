#[test]
fn schema_shapes() {
    let t = |schema: Value| ts(&ty(&schema, &schema, 0), 0);
    assert_eq!(
        t(serde_json::json!({"type": "array", "items": {"type": ["string", "null"]}})),
        "(string | null)[]"
    );
    assert_eq!(t(serde_json::json!({"const": 3})), "3");
    assert_eq!(
        t(serde_json::json!({"type": "string", "nullable": true})),
        "string | null"
    );
    assert_eq!(
        t(
            serde_json::json!({"oneOf": [{"type": "string"}, {"type": "integer"}, {"type": "string"}]})
        ),
        "string | number"
    );
    assert_eq!(
        t(
            serde_json::json!({"type": "array", "prefixItems": [{"type": "string"}, {"type": "number"}]})
        ),
        "[string, number]"
    );
    assert_eq!(t(serde_json::json!({})), "unknown");
    assert_eq!(
        t(serde_json::json!({"type": "object"})),
        "Record<string, unknown>"
    );
    assert_eq!(
        t(serde_json::json!({"type": "object", "additionalProperties": false})),
        "Record<string, never>"
    );
    // `allOf` of objects is one object.
    assert_eq!(
        t(serde_json::json!({"allOf": [
            {"type": "object", "required": ["a"], "properties": {"a": {"type": "string"}}},
            {"type": "object", "properties": {"b": {"type": "boolean"}}}
        ]})),
        "{\n  a: string;\n  b?: boolean;\n}"
    );
    // A schema that refers to itself ends as "anything" instead of looping.
    let tree = serde_json::json!({
        "type": "object",
        "properties": {"children": {"type": "array", "items": {"$ref": "#"}}}
    });
    assert!(t(tree).contains("unknown"));
}

