//! What the serverless targets share: one Node function that runs the whole
//! project on `@unswornjs/sdk/node`. The build writes an entry that imports
//! the handler modules, bundles it into a single file with esbuild, and
//! puts the core's wasm and the `static` routes' files next to it.

use std::path::{Path, PathBuf};
use std::process::Command;

use super::{Prepared, write};

/// The oldest Node the bundle is written for.
pub const NODE_TARGET: &str = "node22";

/// What a function's directory holds, besides the platform's own files.
pub struct Function {
    /// The number of files copied for `static` routes.
    pub assets: usize,
}

/// The entry's source: `import_line`, an import per handler module, and
/// `export default {create}(bundle, options)`, where the options tell the
/// runtime that the wasm and the assets sit next to the bundled file.
pub fn entry(
    p: &Prepared,
    entry_dir: &Path,
    import_line: &str,
    create: &str,
) -> Result<String, String> {
    let (imports, bundle) = p.bundle_js(entry_dir)?;
    let assets = if p.statics.is_empty() {
        ""
    } else {
        "\n  assets: new URL(\"./assets/\", import.meta.url),"
    };
    Ok(format!(
        "// Generated by `unsworn build --target {target}` (unsworn {version}).
// Don't edit: rebuild instead.

{import_line}
{imports}
export default {create}({bundle}, {{
  wasm: new URL(\"./unsworn_bg.wasm\", import.meta.url),{assets}
}});
",
        target = p.target,
        version = unsworn_core::VERSION,
    ))
}

/// Writes `entry` to `<out>/entry.mjs` and builds the function in `dir`:
/// the bundle as `index.mjs` with its source map, `unsworn_bg.wasm`, and
/// `assets/` when the project has `static` routes.
pub fn build(p: &Prepared, dir: &Path, entry: &str) -> Result<Function, String> {
    let source = p.out.join("entry.mjs");
    write(&source, entry)?;
    std::fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", dir.display()))?;

    let esbuild = find_esbuild(&p.root)?;
    let status = Command::new(&esbuild)
        .current_dir(&p.root)
        .arg(&source)
        .arg("--bundle")
        .arg("--platform=node")
        .arg("--format=esm")
        .arg(format!("--target={NODE_TARGET}"))
        .arg("--sourcemap")
        .arg("--log-level=warning")
        // Dependencies written as CommonJS call `require`, which an ES
        // module doesn't have.
        .arg("--banner:js=import { createRequire as __unswornRequire } from \"node:module\"; const require = __unswornRequire(import.meta.url);")
        .arg(format!("--outfile={}", dir.join("index.mjs").display()))
        .status()
        .map_err(|e| format!("{}: {e}", esbuild.display()))?;
    if !status.success() {
        return Err("esbuild couldn't bundle the handlers (see above)".into());
    }

    let wasm = p.sdk.join("wasm/unsworn_bg.wasm");
    std::fs::copy(&wasm, dir.join("unsworn_bg.wasm")).map_err(|e| {
        format!(
            "{}: {e} (is @unswornjs/sdk installed from npm, or its wasm built?)",
            wasm.display()
        )
    })?;
    let assets = p.copy_statics(&dir.join("assets"))?;
    Ok(Function { assets })
}

/// esbuild, from the project's dependencies.
fn find_esbuild(root: &Path) -> Result<PathBuf, String> {
    let name = if cfg!(windows) {
        "esbuild.cmd"
    } else {
        "esbuild"
    };
    root.ancestors()
        .map(|d| d.join("node_modules/.bin").join(name))
        .find(|p| p.exists())
        .ok_or_else(|| {
            "the build bundles handlers with esbuild, which isn't installed; run `npm install --save-dev esbuild`".to_string()
        })
}
