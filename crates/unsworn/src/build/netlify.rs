//! `--target netlify`: a Netlify Function in the Frameworks API's layout,
//! which Netlify deploys along with the site. Written, by default, to
//! `.netlify/v1`:
//!
//! - `functions/unsworn/index.mjs` and what it loads (see
//!   [`super::functions`]): the function, already bundled;
//! - `functions/unsworn/unsworn.mjs`: the file Netlify reads. It exports
//!   the function and its `config`, which routes every path to it (ahead of
//!   static files, so routes' policies apply to files too) and tells
//!   Netlify not to bundle it again.
//!
//! Netlify needs a directory to publish even when the function answers
//! everything, so the build also makes an empty `.netlify/static`.

use serde_json::json;

use super::{Prepared, functions, relative, write};

/// The function's name on Netlify.
const FUNCTION: &str = "unsworn";

/// A directory with nothing in it, for `publish` in `netlify.toml`.
const PUBLISH: &str = ".netlify/static";

pub fn build(p: Prepared) -> Result<(), String> {
    let dir = p.out.join(format!("functions/{FUNCTION}"));
    let entry = functions::entry(
        &p,
        &p.out,
        "import { createNetlifyFunction } from \"@unswornjs/sdk/netlify\";",
        "export default createNetlifyFunction",
    )?;
    let built = functions::build(&p, &dir, &entry)?;

    // Netlify resolves `includedFiles` from the project's directory.
    let included = relative(&p.root, &dir);
    let included = included.strip_prefix("./").unwrap_or(&included);
    write(
        &dir.join(format!("{FUNCTION}.mjs")),
        &main_file(&format!("{included}/**")),
    )?;
    let publish = p.root.join(PUBLISH);
    std::fs::create_dir_all(&publish).map_err(|e| format!("{}: {e}", publish.display()))?;

    p.report(
        built.assets,
        &[
            ("try it:", "npx netlify dev"),
            ("deploy:", "npx netlify deploy --prod"),
        ],
    );
    if !p.root.join("netlify.toml").exists() {
        println!(
            "  netlify.toml needs:  [build] command = \"unsworn build --target netlify\", publish = \"{PUBLISH}\""
        );
    }
    Ok(())
}

/// The function's main file. Netlify reads `config` from the source
/// without running it, so it's written out as a literal here instead of
/// going through the bundler.
fn main_file(included: &str) -> String {
    let config = json!({
        "path": "/*",
        "name": "Unsworn",
        "generator": format!("unsworn@{}", unsworn_core::VERSION),
        "nodeBundler": "none",
        "includedFiles": [included],
    });
    format!(
        "// Generated by `unsworn build --target netlify` (unsworn {version}).
// Don't edit: rebuild instead.

import handler from \"./index.mjs\";

export default handler;

export const config = {config};
",
        version = unsworn_core::VERSION,
        config = serde_json::to_string_pretty(&config).unwrap_or_default(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_main_file_routes_everything_and_ships_its_directory() {
        let text = main_file(".netlify/v1/functions/unsworn/**");
        assert!(text.contains("export default handler;"));
        assert!(text.contains("\"path\": \"/*\""));
        assert!(text.contains("\"nodeBundler\": \"none\""));
        assert!(text.contains("\".netlify/v1/functions/unsworn/**\""));
    }
}
